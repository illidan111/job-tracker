test('malformed localStorage fails gracefully and can be recovered', async ({ page }) => {
  await page.addInitScript(key => { if (!sessionStorage.getItem('corruption-set')) { localStorage.setItem(key, '{broken'); sessionStorage.setItem('corruption-set', 'true') } }, storageKey)
  await page.goto('/')
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(await page.evaluate(key => localStorage.getItem(key), storageKey)).toBe('{broken')
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Import browser data' }).click()
  await expect(page.getByRole('alert')).toContainText('browser backup could not be read')
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('button', { name: 'Reset demo data', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(await applications(page)).toHaveLength(24)
})

