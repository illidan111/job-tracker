test('pointer drag and drop updates the board, dashboard, and storage', async ({ page }) => {
  await page.goto('/kanban')
  const id = (await applications(page)).find(app => app.company === 'Vercel')!.id
  const source = page.getByTestId(`card-${id}`).getByRole('button', { name: /Drag Vercel application/ })
  const target = page.getByTestId('column-SCREENING')
  const start = await source.boundingBox()
  const end = await target.boundingBox()
  expect(start).not.toBeNull()
  expect(end).not.toBeNull()
  await page.mouse.move(start!.x + start!.width / 2, start!.y + start!.height / 2)
  await page.mouse.down()
  await page.mouse.move(start!.x + 10, start!.y + 12, { steps: 5 })
  await page.mouse.move(end!.x + end!.width / 2, end!.y + 70, { steps: 20 })
  await expect(target).toHaveClass(/is-over/)
  await page.mouse.up()
  await expect(target.getByTestId(`card-${id}`)).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('column-SCREENING').getByTestId(`card-${id}`)).toBeVisible()
  await page.goto('/')
  await expect(page.locator('.route-stations a').filter({ hasText: 'In conversation' }).locator('strong')).toHaveText('8')
})

test('export, invalid import, valid import, reset and clear confirmation', async ({ page }) => {
  await page.goto('/settings')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const download = await downloadPromise
  const file = await download.path()
  const original = JSON.parse(await readFile(file!, 'utf8')) as { version: number; applications: { company: string }[]; career?: unknown }
  expect(original.version).toBe(4)
  expect(original.applications).toHaveLength(24)
  await page.getByLabel('Import applications file').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(page.getByRole('alert')).toContainText('Your existing data is unchanged')
  expect(await applications(page)).toHaveLength(24)
  // Exercise legacy import compatibility independently of v4 relationship restoration.
  original.version = 3
  delete original.career
  original.applications[0].company = 'Restored Company'
  await page.getByLabel('Import applications file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  await expect(page.getByRole('dialog', { name: 'Replace your workspace?' })).toBeVisible()
  await page.getByRole('button', { name: 'Replace & import', exact: true }).click()
  await page.reload()
  expect((await applications(page))[0].company).toBe('Restored Company')
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('button', { name: 'Reset demo data', exact: true }).click()
  expect((await applications(page)).some(app => app.company === 'Linear')).toBe(true)
  await page.getByRole('button', { name: 'Clear data', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await applications(page)).toHaveLength(24)
  await page.getByRole('button', { name: 'Clear data', exact: true }).click()
  await page.getByRole('button', { name: 'Clear all applications', exact: true }).click()
  await page.reload()
  expect(await applications(page)).toHaveLength(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find your starting point' })).toBeVisible()
  await page.goto('/analytics')
  await expect(page.getByText('0 of 0 reached an interview')).toBeVisible()
  await page.goto('/kanban')
  await expect(page.locator('.kanban-card')).toHaveCount(0)
})

