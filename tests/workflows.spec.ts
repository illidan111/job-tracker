import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { signup, workspace } from './helpers'
test.beforeEach(async ({ page }) => { await signup(page) })

const storageKey = 'waypoint.workspace.v1'
async function applications(page: Page) {
  return (await workspace(page)).applications
}
async function addApplication(page: Page, company: string) {
  await page.getByRole('button', { name: 'Add application', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: 'Add application' })
  await dialog.getByLabel('Company *', { exact: true }).fill(company)
  await dialog.getByLabel('Position *', { exact: true }).fill('Frontend Engineer')
  await dialog.getByLabel('Location', { exact: true }).fill('Astana')
  await dialog.getByLabel('Annual salary (USD)', { exact: true }).fill('90000')
  await dialog.getByRole('button', { name: 'Add application', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}

