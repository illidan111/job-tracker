test('unsaved forms confirm discard and dialogs retain keyboard focus', async ({ page }) => {
  await page.goto('/')
  const opener = page.getByRole('button', { name: 'Add application', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Add application' })
  await dialog.getByLabel('Company *', { exact: true }).fill('Unsaved Co')
  await page.keyboard.press('Escape')
  const confirm = page.getByRole('dialog', { name: 'Discard your changes?' })
  await expect(confirm).toBeVisible()
  await confirm.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await confirm.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
  expect(await applications(page)).toHaveLength(24)
})

